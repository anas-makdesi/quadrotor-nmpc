"""Generate the acados solver C code and a parameter header for the ROS 2 package.

    python scripts/export_c_code.py [--out ros2/quadrotor_nmpc_ros/generated]

Writes <out>/c_generated_code/ (acados solver "quadrotor_nmpc") and <out>/quad_params.hpp
(vehicle constants, mixer and its inverse, horizon grid) so that the C++ plant, reference
and controller use exactly the numbers the Python package uses.
"""
from __future__ import annotations

import argparse
import sys
import warnings
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
warnings.filterwarnings("ignore")

from qnmpc.nmpc import NMPCConfig, build_ocp  # noqa: E402
from qnmpc.params import Quad  # noqa: E402


def arr(v):
    return "{" + ", ".join(f"{float(x):.17g}" for x in np.ravel(v)) + "}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "ros2" / "quadrotor_nmpc_ros" / "generated"))
    out = Path(ap.parse_args().out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    from acados_template import AcadosOcpSolver

    q, cfg = Quad(), NMPCConfig(name="quadrotor_nmpc")
    ocp = build_ocp(q, cfg)
    ocp.name = "quadrotor_nmpc"
    ocp.code_export_directory = str(out / "c_generated_code")
    ocp.json_file = str(out / "c_generated_code" / "quadrotor_nmpc.json")
    AcadosOcpSolver.generate(ocp, verbose=False)
    hdr = f"""// generated by scripts/export_c_code.py - do not edit
#pragma once
namespace quadrotor_nmpc {{
namespace params {{
constexpr double m = {q.m!r};
constexpr double J[3] = {arr(q.J)};
constexpr double drag[3] = {arr(q.drag)};
constexpr double T_min = {q.T_min!r};
constexpr double T_max = {q.T_max!r};
constexpr double tau_motor = {q.tau_motor!r};
constexpr double g = 9.81;
constexpr double mixer[16] = {arr(q.mixer)};      // row-major 4x4
constexpr double mixer_inv[16] = {arr(np.linalg.inv(q.mixer))};
constexpr int N = {cfg.N};
constexpr double time_steps[{cfg.N}] = {arr(cfg.time_steps)};
}}  // namespace params
}}  // namespace quadrotor_nmpc
"""
    (out / "quad_params.hpp").write_text(hdr)
    print(f"exported to {out}")


if __name__ == "__main__":
    main()
